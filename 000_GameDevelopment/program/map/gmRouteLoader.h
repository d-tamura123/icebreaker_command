// gmRouteLoader.h
#pragma once
#include <cstdint>
#include <vector>
#include <dxe.h>
#include "../gmGameConfig.h"

namespace gm
{
    // ------------------------------------------------------------
    // route_*.bin 専用ローダー(1ファイル = 1航路ぶんのウェイポイントデータ)。
    //
    // Excel側の航路シート(Route_1, Route_2, ...)と同じ256×256のマス目に対応する
    // 固定サイズ(256×256×1byte)の生バイナリで、map.binと同じ「マス目をそのまま
    // 生バイナリに焼く」流儀を踏襲している。ただし中身はビットフラグではなく、
    // 「そのマスが航路上の何番目のウェイポイントか」を表す順序値になっている。
    //
    // 【エンコード規則】(IC_ExcelMapTool側 modRouteExporter.bas と対応。変更する場合は両方揃えること)
    //   0     : このマスは航路データではない(未使用)
    //   1     : 始点(S)。ウェイポイント順序としては0番目に対応
    //   2以上 : 値から1を引いた数が、そのウェイポイントの順序(1,2,3,...)
    //           終点(G)も、連番の最大値+1番目のウェイポイントとしてこの規則にそのまま従う
    //   ※ 0(未使用)と始点(本来の順序0)が衝突しないよう、実際の順序に+1したものを
    //     ファイルへ書き込んでいる。符号なしbyteのまま始点/終点を表現するためのオフセットであり、
    //     マイナス値や別のデータ型は使わない。
    class gmRouteLoader
    {
    public:
        // 1ファイルぶんの航路データを読み込み、マス走査で見つけたウェイポイントを
        // 順序どおりに並べ替えて返す。
        // arg1... 読み込む route_*.bin のファイルパス
        // arg2... 読み込んだウェイポイントのセル座標を、始点(S)→終点(G)の順序で格納する出力先
        // 戻り値: ファイルが開けなければfalse(=そのインデックスの航路ファイルが存在しない、を意味する)
        bool Load(const char* filePath, std::vector<tnl::Vector2i>& outWaypointCellsInOrder);
    };
}
